"""Rebuilds brain.md: an index of every Markdown file in the repository.

Runs from the Stop hook. Skips archive/ folders and dependency, build and data
folders. Writes the file only when its content changes.
"""

import os
import sys
from pathlib import Path

SKIP_DIRS = {".git", ".venv", "node_modules", "data", "archive", "dist", "__pycache__"}
INDEX_NAME = "brain.md"


def find_markdown(root: Path) -> list[str]:
    found = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for name in filenames:
            if name.endswith(".md") and name != INDEX_NAME:
                found.append((Path(dirpath) / name).relative_to(root).as_posix())
    return sorted(found)


def render(files: list[str]) -> str:
    lines = [
        "# Brain",
        "",
        "Index of all Markdown files in this repository. Generated by `.claude/hooks/brain.py`.",
        "",
    ]
    lines += [f"- [[{path}]]" for path in files]
    return "\n".join(lines) + "\n"


def main() -> int:
    root = Path(
        os.environ.get("CLAUDE_PROJECT_DIR", Path(__file__).resolve().parents[2])
    )
    target = root / INDEX_NAME
    content = render(find_markdown(root))
    if not target.exists() or target.read_text(encoding="utf-8") != content:
        target.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
